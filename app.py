# =========================================================

def update_existing_anomalies(user_id):

    connection = get_db_connection()

    transactions = connection.execute(
        """
        SELECT
            id,
            amount
        FROM expenses
        WHERE user_id = %s
        ORDER BY date, id
        """,
        (user_id,)
    ).fetchall()

    # Existing transactions can be checked
    # when the user has at least 5 expenses
    if len(transactions) < 5:

        connection.execute(
            """
            UPDATE expenses
            SET anomaly_status = 'Normal'
            WHERE user_id = %s
            """,
            (user_id,)
        )

        connection.commit()

        connection.close()

        return

    amounts = [
        float(row["amount"])
        for row in transactions
    ]

    # Check every existing transaction
    for index, transaction in enumerate(transactions):

        transaction_id = transaction["id"]

        transaction_amount = float(
            transaction["amount"]
        )

        # Remove the current transaction
        # from its own history
        history = (
            amounts[:index]
            + amounts[index + 1:]
        )

        # Need at least 4 other expenses
        if len(history) < 4:

            anomaly_status = "Normal"

        else:

            history_array = np.array(
                history,
                dtype=float
            )

            history_data = pd.DataFrame({

                "Amount": history_array,

                "Amount_Log": np.log1p(
                    history_array
                )

            })

            model = IsolationForest(

                n_estimators=200,

                contamination="auto",

                random_state=42

            )

            model.fit(history_data)

            transaction_data = pd.DataFrame({

                "Amount": [
                    transaction_amount
                ],

                "Amount_Log": [
                    np.log1p(
                        transaction_amount
                    )
                ]

            })

            transaction_score = (
                model.decision_function(
                    transaction_data
                )[0]
            )

            history_scores = (
                model.decision_function(
                    history_data
                )
            )

            # Changed from 5% to 15%
            # This allows multiple unusual transactions
            score_limit = np.percentile(
                history_scores,
                15
            )

            if transaction_score < score_limit:

                anomaly_status = "Unusual"

            else:

                anomaly_status = "Normal"

        connection.execute(
            """
            UPDATE expenses
            SET anomaly_status = %s
            WHERE id = %s
            AND user_id = %s
            """,
            (
                anomaly_status,
                transaction_id,
                user_id
            )
        )

    connection.commit()

    connection.close()


