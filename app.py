    connection = get_db_connection()

    try:

        expenses = connection.execute(
            """
            SELECT *
            FROM expenses
            WHERE user_id = %s
            ORDER BY date
            """,
            (user_id,)
        ).fetchall()

        if expenses:

            user_expenses = pd.DataFrame(
                [dict(row) for row in expenses]
            )

        else:

            user_expenses = pd.DataFrame(
                columns=[
                    "id",
                    "date",
                    "description",
                    "amount",
                    "category",
                    "anomaly_status",
                    "user_id"
                ]
            )

        predicted_next_month = None

        prediction_method = None

        if not user_expenses.empty:

            prediction_result = (
                predict_next_month(
                    user_expenses
                )
            )

            this_month = (
                prediction_result[
                    "current_total"
                ]
            )

            previous_total = (
                prediction_result[
                    "previous_month_total"
                ]
            )

            predicted_next_month = (
                prediction_result[
                    "prediction"
                ]
            )

            prediction_method = (
                prediction_result[
                    "method"
                ]
            )

            if previous_total > 0:

                last_month_spending = (
                    previous_total
                )

            else:

                last_month_spending = None

        else:

            this_month = 0

            last_month_spending = None

        spending_change = None

        spending_change_percentage = None

        if (
            last_month_spending is not None
            and last_month_spending > 0
        ):

            spending_change = (
                this_month
                - last_month_spending
            )

            spending_change_percentage = (
                spending_change
                / last_month_spending
            ) * 100

        if user_expenses.empty:

            spending_insight = (
                "Add some expenses to start "
                "getting spending insights."
            )

        elif predicted_next_month is None:

            spending_insight = (
                "Add a few more expenses to get "
                "a more reliable next-month prediction."
            )

        elif last_month_spending is not None:

            if spending_change > 0:

                spending_insight = (
                    f"Your spending increased by "
                    f"{abs(spending_change_percentage):.2f}% "
                    f"compared with last month."
                )

            elif spending_change < 0:

                spending_insight = (
                    f"Your spending decreased by "
                    f"{abs(spending_change_percentage):.2f}% "
                    f"compared with last month."
                )

            else:

                spending_insight = (
                    "Your spending is almost the "
                    "same as last month."
                )

        elif this_month > 0:

            prediction_change_percentage = (
                (
                    predicted_next_month
                    - this_month
                )
                / this_month
            ) * 100

            if prediction_change_percentage > 1:

                spending_insight = (
                    f"Your predicted next-month "
                    f"spending is "
                    f"{prediction_change_percentage:.2f}% "
                    f"higher than this month."
                )

            elif prediction_change_percentage < -1:

                spending_insight = (
                    f"Your predicted next-month "
                    f"spending is "
                    f"{abs(prediction_change_percentage):.2f}% "
                    f"lower than this month."
                )

            else:

                spending_insight = (
                    "Your predicted next-month "
                    "spending is nearly the same "
                    "as this month."
                )

        else:

            spending_insight = (
                "Keep recording expenses to get "
                "more personalized spending insights."
            )

    finally:

        release_db_connection(connection)

    return render_template(

        "prediction.html",

        username=session.get(
            "username"
        ),

        this_month=
            this_month,

        last_month_spending=
            last_month_spending,

        predicted_next_month=
            predicted_next_month,

        spending_change=
            spending_change,

        spending_change_percentage=
            spending_change_percentage,

        spending_insight=
            spending_insight,

        prediction_method=
            prediction_method
    )


