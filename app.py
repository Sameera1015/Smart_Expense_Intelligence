# CHECK EXISTING TRANSACTIONS
# =========================================================

def update_existing_anomalies(user_id):

    total_start = time.perf_counter()

    connection = get_db_connection()

    try:

        # =====================================================
        # DATABASE FETCH TIMING
        # =====================================================

        db_start = time.perf_counter()

        transactions = connection.execute(
            """
            SELECT
                id,
                amount
            FROM expenses
            WHERE user_id = %s
            ORDER BY date, id
            """,
            (user_id,)
        ).fetchall()

        db_fetch_time = (
            time.perf_counter()
            - db_start
        )

        print(
            f"ANOMALY: database fetch = "
            f"{db_fetch_time:.3f} sec"
        )

        print(
            f"ANOMALY: transaction count = "
            f"{len(transactions)}"
        )

        # =====================================================
        # LESS THAN 5 TRANSACTIONS
        # =====================================================

        if len(transactions) < 5:

            db_start = time.perf_counter()

            connection.execute(
                """
                UPDATE expenses
                SET anomaly_status = 'Normal'
                WHERE user_id = %s
                """,
                (user_id,)
            )

            connection.execute(
                """
                INSERT INTO user_anomaly_state
                (
                    user_id,
                    needs_refresh
                )
                VALUES (%s, FALSE)

                ON CONFLICT (user_id)
                DO UPDATE SET
                    needs_refresh = FALSE
                """,
                (user_id,)
            )

            connection.commit()

            db_write_time = (
                time.perf_counter()
                - db_start
            )

            print(
                f"ANOMALY: database write = "
                f"{db_write_time:.3f} sec"
            )

            total_time = (
                time.perf_counter()
                - total_start
            )

            print(
                f"ANOMALY: TOTAL = "
                f"{total_time:.3f} sec"
            )

            return

        # =====================================================
        # PREPARE AMOUNTS
        # =====================================================

        amounts = [
            float(row["amount"])
            for row in transactions
        ]

        # =====================================================
        # PREPARE CALCULATIONS
        # =====================================================

        calculation_start = time.perf_counter()

        calculation_jobs = []

        for index, transaction in enumerate(
            transactions
        ):

            calculation_jobs.append({

                "id":
                    transaction["id"],

                "amount":
                    transaction["amount"],

                "index":
                    index,

                "amounts":
                    amounts

            })

        # =====================================================
        # PARALLEL CALCULATION
        # =====================================================

        worker_count = min(
            4,
            len(calculation_jobs)
        )

        with ThreadPoolExecutor(
            max_workers=worker_count
        ) as executor:

            results = list(
                executor.map(
                    calculate_existing_anomaly,
                    calculation_jobs
                )
            )

        calculation_time = (
            time.perf_counter()
            - calculation_start
        )

        print(
            f"ANOMALY: Isolation Forest calculations = "
            f"{calculation_time:.3f} sec"
        )

        # =====================================================
        # DATABASE UPDATE TIMING
        # =====================================================

        db_write_start = time.perf_counter()

        # =====================================================
        # BATCH DATABASE UPDATE
        # =====================================================
        # psycopg3 executemany() is a cursor method.
        # The anomaly calculation itself is unchanged.

        with connection.cursor() as cursor:

            cursor.executemany(
                """
                UPDATE expenses
                SET anomaly_status = %s
                WHERE id = %s
                AND user_id = %s
                """,
                [
                    (
                        anomaly_status,
                        transaction_id,
                        user_id
                    )
                    for transaction_id, anomaly_status in results
                ]
            )

        connection.execute(
            """
            INSERT INTO user_anomaly_state
            (
                user_id,
                needs_refresh
            )
            VALUES (%s, FALSE)

            ON CONFLICT (user_id)
            DO UPDATE SET
                needs_refresh = FALSE
            """,
            (user_id,)
        )

        connection.commit()

        db_write_time = (
            time.perf_counter()
            - db_write_start
        )

        print(
            f"ANOMALY: database updates = "
            f"{db_write_time:.3f} sec"
        )

        # =====================================================
        # TOTAL TIMING
        # =====================================================

        total_time = (
            time.perf_counter()
            - total_start
        )

        print(
            f"ANOMALY: TOTAL = "
            f"{total_time:.3f} sec"
        )

    finally:

        release_db_connection(connection)


