# PERSONALIZED ISOLATION FOREST
# CHECK NEW TRANSACTION
# =========================================================

def final_anomaly_check(history, new_amount):

    history = np.array(
        history,
        dtype=float
    )

    # New transaction needs at least
    # 10 previous personal expenses
    if len(history) < 10:

        return "Not enough history"

    history_data = pd.DataFrame({

        "Amount": history,

        "Amount_Log": np.log1p(history)

    })

    model = IsolationForest(

        n_estimators=200,

        contamination="auto",

        random_state=42

    )

    model.fit(history_data)

    new_data = pd.DataFrame({

        "Amount": [new_amount],

        "Amount_Log": [
            np.log1p(new_amount)
        ]

    })

    score = model.decision_function(
        new_data
    )[0]

    history_scores = model.decision_function(
        history_data
    )

    # 15% threshold
    score_limit = np.percentile(
        history_scores,
        15
    )

    if score < score_limit:

        return "Unusual"

    return "Normal"


# =========================================================
# CALCULATE ONE EXISTING TRANSACTION
# =========================================================

def calculate_existing_anomaly(transaction):

    transaction_id = transaction["id"]

    transaction_amount = float(
        transaction["amount"]
    )

    amounts = transaction["amounts"]

    index = transaction["index"]

    # Remove the current transaction
    # from its own history
    history = (
        amounts[:index]
        + amounts[index + 1:]
    )

    # Need at least 4 other expenses
    if len(history) < 4:

        return (
            transaction_id,
            "Normal"
        )

    history_array = np.array(
        history,
        dtype=float
    )

    history_data = pd.DataFrame({

        "Amount": history_array,

        "Amount_Log": np.log1p(
            history_array
        )

    })

    # SAME Isolation Forest SETTINGS
    model = IsolationForest(

        n_estimators=200,

        contamination="auto",

        random_state=42

    )

    model.fit(history_data)

    transaction_data = pd.DataFrame({

        "Amount": [
            transaction_amount
        ],

        "Amount_Log": [
            np.log1p(
                transaction_amount
            )
        ]

    })

    transaction_score = (
        model.decision_function(
            transaction_data
        )[0]
    )

    history_scores = (
        model.decision_function(
            history_data
        )
    )

    # SAME 15% threshold
    score_limit = np.percentile(
        history_scores,
        15
    )

    if transaction_score < score_limit:

        anomaly_status = "Unusual"

    else:

        anomaly_status = "Normal"

    return (
        transaction_id,
        anomaly_status
    )


