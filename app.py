# NEXT MONTH PREDICTION
# =========================================================

def predict_next_month(user_expenses):

    data = user_expenses.copy()

    data["date"] = pd.to_datetime(
        data["date"]
    )

    current_month = (
        data["date"].max().to_period("M")
    )

    current_data = data[
        data["date"].dt.to_period("M")
        == current_month
    ]

    current_total = current_data[
        "amount"
    ].sum()

    previous_month = current_month - 1

    previous_data = data[
        data["date"].dt.to_period("M")
        == previous_month
    ]

    previous_month_total = previous_data[
        "amount"
    ].sum()

    transaction_count = len(
        current_data
    )

    previous_transaction_count = len(
        previous_data
    )

    # Need at least 3 transactions
    # in the current month
    if transaction_count < 3:

        return {

            "current_total":
                current_total,

            "previous_month_total":
                previous_month_total,

            "prediction":
                None,

            "method":
                "Not enough expense data"
        }

    # =====================================================
    # HANDLE PREVIOUS MONTH
    # =====================================================

    if previous_data.empty:

        model_previous_spending = current_total

        model_previous_transaction_count = (
            transaction_count
        )

        method = (
            "Random Forest using "
            "current-month spending "
            "(previous month unavailable)"
        )

    else:

        model_previous_spending = (
            previous_month_total
        )

        model_previous_transaction_count = (
            previous_transaction_count
        )

        method = (
            "Random Forest using "
            "current + previous month"
        )

    # =====================================================
    # CREATE MODEL INPUT
    # =====================================================

    features = pd.DataFrame([{

        "monthly_spending":
            current_total,

        "previous_month_spending":
            model_previous_spending,

        "transaction_count":
            transaction_count,

        "previous_transaction_count":
            model_previous_transaction_count,

        "month":
            current_month.month

    }])

    print("\nPrediction features:")
    print(features)

    # =====================================================
    # RANDOM FOREST PREDICTION
    # =====================================================

    prediction = regression_model.predict(
        features
    )[0]

    prediction = max(
        0,
        float(prediction)
    )

    return {

        "current_total":
            current_total,

        "previous_month_total":
            previous_month_total,

        "prediction":
            prediction,

        "method":
            method
    }


