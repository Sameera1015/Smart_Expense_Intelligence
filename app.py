def final_anomaly_check(history, new_amount):

    history = np.array(
        history,
        dtype=float
    )

    # New transaction needs at least
    # 10 previous personal expenses
    if len(history) < 10:

        return "Not enough history"

    history_data = pd.DataFrame({

        "Amount": history,

        "Amount_Log": np.log1p(history)

    })

    model = IsolationForest(

        n_estimators=200,

        contamination="auto",

        random_state=42

    )

    model.fit(history_data)

    new_data = pd.DataFrame({

        "Amount": [new_amount],

        "Amount_Log": [
            np.log1p(new_amount)
        ]

    })

    score = model.decision_function(
        new_data
    )[0]

    history_scores = model.decision_function(
        history_data
    )

    # Changed from 5% to 15%
    # This allows multiple unusual transactions
    score_limit = np.percentile(
        history_scores,
        15
    )

    if score < score_limit:

        return "Unusual"

    return "Normal"


