# ADD EXPENSE
# =========================================================

@app.route(
    "/add-expense",
    methods=["GET", "POST"]
)
def add_expense():

    if "user_id" not in session:

        return redirect("/login")

    if request.method == "GET":

        return render_template(
            "index.html",
            username=session.get("username")
        )

    user_id = session["user_id"]

    # =====================================================
    # GET EXPENSE DATE FROM FORM
    # =====================================================

    expense_date = request.form[
        "expense_date"
    ]

    description = request.form[
        "description"
    ]

    amount = float(
        request.form["amount"]
    )

    payment_method = request.form[
        "payment_method"
    ]

    time_of_day = request.form[
        "time_of_day"
    ]

    # =====================================================
    # CATEGORY PREDICTION
    # =====================================================

    description_tfidf = (
        tfidf_vectorizer.transform(
            [description]
        )
    )

    category = (
        category_model.predict(
            description_tfidf
        )[0]
    )

    # =====================================================
    # GET USER HISTORY
    # =====================================================

    connection = get_db_connection()

    previous_expenses = connection.execute(
        """
        SELECT amount
        FROM expenses
        WHERE user_id = %s
        ORDER BY date, id
        """,
        (user_id,)
    ).fetchall()

    user_history = [
        row["amount"]
        for row in previous_expenses
    ]

    # =====================================================
    # CHECK NEW EXPENSE
    # =====================================================

    anomaly_status = final_anomaly_check(
        user_history,
        amount
    )

    if anomaly_status == "Not enough history":

        anomaly_status = "Normal"

    # =====================================================
    # STORE NEW EXPENSE
    # =====================================================

    connection.execute(
        """
        INSERT INTO expenses
        (
            date,
            description,
            amount,
            category,
            anomaly_status,
            user_id
        )
        VALUES (%s, %s, %s, %s, %s, %s)
        """,
        (
            expense_date,
            description,
            amount,
            category,
            anomaly_status,
            user_id
        )
    )

    connection.commit()

    connection.close()

    # =====================================================
    # PERFORMANCE CHANGE
    # =====================================================
    # We intentionally do NOT call
    # update_existing_anomalies() here.
    #
    # The new expense already has its anomaly status
    # from final_anomaly_check().
    #
    # This prevents Isolation Forest from being
    # recalculated for every previous transaction
    # whenever a new expense is added.
    # =====================================================

    # =====================================================
    # RESULT PAGE
    # =====================================================

    result_data = {

        "description":
            description,

        "amount":
            amount,

        "category":
            category,

        "payment_method":
            payment_method,

        "time_of_day":
            time_of_day,

        "anomaly_status":
            anomaly_status
    }

    result_url = (
        "/result?"
        + urlencode(result_data)
    )

    return redirect(
        result_url
    )


